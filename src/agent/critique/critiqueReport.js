import { IST_TIMEZONE, localDateTimeOf } from "../../tools/mongo/dateUtils.js";

/**
 * The critique rendered as the markdown file that lands in the repo.
 *
 * Pure, and deliberately dumb: every judgement was made upstream, so this is
 * the one piece of the pass with no model in it and no way to be wrong about
 * the day. It exists as its own module because the report is an interface — a
 * scheduled coding session reads these files — and an interface deserves a
 * guard that does not need a database or an API key to run.
 */

const KIND_LABEL = {
    hallucination: "hallucination",
    bug: "bug",
    improvement: "improvement",
};

const COUNTS_MARKER = "<!-- critique:";

function block(finding, n) {
    // A db-proven finding is labelled as such in the heading, because it changes
    // what the reader should do: there is nothing to second-guess, the row is
    // not where the agent said it was.
    const proven = finding.source === "db" ? " · PROVEN against the database" : "";
    const lines = [
        `### ${n}. ${finding.severity.toUpperCase()} · ${KIND_LABEL[finding.kind]} · ${finding.turn}${proven}`,
        "",
        finding.summary,
        "",
        `> ${finding.evidence}`,
    ];
    // Said plainly rather than left implicit: a paraphrased quote is still
    // worth reading, but it is not proof, and whoever acts on it should open
    // the turn first.
    if (!finding.quoted) lines.push("", "_Quote not found verbatim in the input — check the turn before acting._");
    if (finding.suggestion) lines.push("", `**Suggested fix** — ${finding.suggestion}`);
    return lines.join("\n");
}

/**
 * @param {object}   args.critique  the coerced critique
 * @param {object[]} args.turns     [{id, source, at}] as rendered
 * @returns {string} the whole file
 */
export function renderCritiqueReport({
    userId, logDate, critique, turns = [], model = "unknown", verification = null,
    timeZone = IST_TIMEZONE, generatedAt = new Date(),
}) {
    const { satisfaction, findings, wentWell, dropped } = critique;
    const proven = findings.filter(f => f.source === "db").length;
    const counts = findings.reduce((acc, f) => ({ ...acc, [f.severity]: (acc[f.severity] ?? 0) + 1 }), {});

    const out = [
        `# Agent self-critique — ${logDate}`,
        "",
        `- **User** ${userId}`,
        `- **Turns reviewed** ${turns.length}`,
        `- **Satisfaction** ${satisfaction.score === null ? "not scored (too little to judge)" : `${satisfaction.score}/5`}${satisfaction.why ? ` — ${satisfaction.why}` : ""}`,
        `- **Critic** ${model}`,
        `- **Writes verified** ${verification ? verification.summary : "not run"}`,
        `- **Generated** ${localDateTimeOf(generatedAt, timeZone)}`,
        "",
        "Generated by Rasmalai's own nightly critique job. Every finding cites the turn it",
        "came from; open that turn in the day's history before changing anything.",
        "",
    ];

    if (!findings.length) {
        out.push("## Findings", "", "None. The critic read the day and had nothing to report.", "");
    } else {
        out.push(`## Findings (${findings.length})`, "");
        findings.forEach((f, i) => out.push(block(f, i + 1), ""));
    }

    if (wentWell.length) {
        out.push("## What went well", "", ...wentWell.map(w => `- ${w}`), "");
    }

    if (verification?.block) {
        // In full, not just the counts. It is the evidence behind every PROVEN
        // finding above, and it is also the only record of what could NOT be
        // checked — which a reader needs in order to know what this pass did
        // not cover.
        out.push("## Write verification", "", "```", verification.block, "```", "");
    }

    if (turns.length) {
        out.push("## Turns reviewed", "", "| turn | time | source |", "| --- | --- | --- |");
        for (const t of turns) {
            const time = new Date(t.at).toLocaleTimeString("en-GB", { timeZone, hour: "2-digit", minute: "2-digit" });
            out.push(`| ${t.id} | ${time} | ${t.source} |`);
        }
        out.push("");
    }

    if (dropped?.length) {
        // Kept in the file because a critic that keeps citing turns that do not
        // exist is itself the finding, and nothing else would surface it.
        out.push("## Discarded by the coercer", "", ...dropped.map(d => `- ${d}`), "");
    }

    // The line a scheduled fix session greps to decide whether there is work,
    // without reading or re-reasoning over the prose above it.
    out.push(
        `${COUNTS_MARKER} date=${logDate} user=${userId} findings=${findings.length} ` +
        `high=${counts.high ?? 0} medium=${counts.medium ?? 0} low=${counts.low ?? 0} proven=${proven} -->`
    );

    return out.join("\n");
}

/** Read the footer back. Returns null for a file that has none. */
export function parseCritiqueCounts(text) {
    const m = String(text).match(/<!-- critique: (.+?) -->/);
    if (!m) return null;
    const out = {};
    for (const pair of m[1].trim().split(/\s+/)) {
        const [k, v] = pair.split("=");
        out[k] = /^\d+$/.test(v) ? Number(v) : v;
    }
    return out;
}
